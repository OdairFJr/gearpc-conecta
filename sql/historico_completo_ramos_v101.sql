-- GEArPC Conecta v101: histórico de permanência e de eventos em cada ramo.
-- Nenhuma data de entrada ou passagem é inferida.
create table if not exists public.jovem_historico_ramos (
  id bigint generated by default as identity primary key,
  jovem_id bigint not null references public.jovens(id) on delete cascade,
  ramo_id bigint not null references public.ramos(id),
  data_ingresso date,
  data_acolhida date,
  data_promessa date,
  data_inicio_caminho date,
  data_passagem date,
  origem text not null default 'manual' check (origem in ('manual','legado_a_conferir')),
  atualizado_em timestamptz not null default now(),
  alterado_por uuid,
  unique(jovem_id,ramo_id),
  constraint datas_ingresso_passagem_coerentes check (
    data_ingresso is null or data_passagem is null or data_passagem >= data_ingresso
  )
);
create index if not exists jovem_historico_ramos_jovem_idx
  on public.jovem_historico_ramos(jovem_id);

alter table public.jovem_historico_ramos enable row level security;
revoke all on public.jovem_historico_ramos from public,anon,authenticated;
grant select on public.jovem_historico_ramos to authenticated;
drop policy if exists "historico_ramos_consulta_autorizada" on public.jovem_historico_ramos;
create policy "historico_ramos_consulta_autorizada"
  on public.jovem_historico_ramos for select to authenticated
  using (exists(
    select 1 from public.jovens j
    where j.id=jovem_id and private.posso_ver_jovem(j.id)
  ));

-- Datas legadas de promessa de Lobinho pertencem inequivocamente a esse ramo.
insert into public.jovem_historico_ramos
(jovem_id,ramo_id,data_promessa,origem)
select id,2,data_promessa_lobinho,'legado_a_conferir'
from public.jovens where data_promessa_lobinho is not null
on conflict (jovem_id,ramo_id) do nothing;

-- Promessa Escoteira antiga só é associada automaticamente ao ramo Escoteiro
-- quando este já é o ramo atual. Para Sênior/Pioneiro, sua origem exige conferência.
insert into public.jovem_historico_ramos
(jovem_id,ramo_id,data_promessa,origem)
select id,3,data_promessa_escoteira,'legado_a_conferir'
from public.jovens where ramo_id=3 and data_promessa_escoteira is not null
on conflict (jovem_id,ramo_id) do nothing;

-- O cadastro antigo não registra ramo/data de ingresso e pode conter acolhida
-- geral do grupo. Importamos os eventos do ramo atual para revisão posterior,
-- sem inventar datas de ingresso e sem substituir promessas já classificadas.
insert into public.jovem_historico_ramos
(jovem_id,ramo_id,data_acolhida,data_inicio_caminho,data_passagem,origem)
select id,ramo_id,data_acolhida,data_inicio_caminho,data_passagem_ramo,'legado_a_conferir'
from public.jovens
where (data_acolhida is not null or data_inicio_caminho is not null
  or data_passagem_ramo is not null)
  and ramo_id between 1 and 5
on conflict (jovem_id,ramo_id) do update
set data_acolhida=coalesce(public.jovem_historico_ramos.data_acolhida,excluded.data_acolhida),
    data_inicio_caminho=coalesce(public.jovem_historico_ramos.data_inicio_caminho,excluded.data_inicio_caminho),
    data_passagem=coalesce(public.jovem_historico_ramos.data_passagem,excluded.data_passagem);

-- Escrita exclusiva pela RPC: perfil administrador ou chefe vinculado à seção
-- atual do jovem. O histórico de ramos passados é editável pela chefia atual.
-- Timestamp de versão evita sobrescrita de alterações concorrentes.
create or replace function public.salvar_historico_ramo_jovem_v101(
  p_jovem_id bigint,
  p_ramo_id bigint,
  p_data_ingresso date,
  p_data_acolhida date,
  p_data_promessa date,
  p_data_inicio_caminho date,
  p_data_passagem date,
  p_versao_esperada timestamptz default null
)
returns jsonb
language plpgsql
security definer
set search_path=''
as $body$
declare
  v_secao_id bigint;
  v_ramo_atual bigint;
  v_admin boolean;
  v_chefia boolean;
  v_old public.jovem_historico_ramos%rowtype;
  v_saved public.jovem_historico_ramos%rowtype;
begin
  if auth.uid() is null then
    raise exception 'É necessário entrar no aplicativo' using errcode='42501';
  end if;

  if p_ramo_id not between 1 and 5 then
    raise exception 'Ramo inválido';
  end if;

  select secao_id,ramo_id into v_secao_id,v_ramo_atual
  from public.jovens where id=p_jovem_id for update;
  if not found or v_secao_id is null then
    raise exception 'Jovem inexistente ou sem seção' using errcode='42501';
  end if;

  v_admin:=private.sou_admin();
  select exists(
    select 1 from public.perfis_usuarios p
    join public.chefe_secoes cs on cs.chefe_id=p.chefe_id
    where p.user_id=auth.uid() and p.ativo
      and p.tipo='chefia' and cs.secao_id=v_secao_id
  ) into v_chefia;

  if not (v_admin or v_chefia) then
    raise exception 'Sem permissão para alterar o histórico deste jovem'
      using errcode='42501';
  end if;

  if p_ramo_id=1 and p_data_promessa is not null then
    raise exception 'O campo de promessa não se aplica ao ramo Filhotes';
  end if;

  if p_data_ingresso is not null and p_data_passagem is not null
    and p_data_passagem<p_data_ingresso then
    raise exception 'Passagem não pode ser anterior ao ingresso';
  end if;

  select * into v_old from public.jovem_historico_ramos
  where jovem_id=p_jovem_id and ramo_id=p_ramo_id for update;
  if found then
    if p_versao_esperada is distinct from v_old.atualizado_em then
      raise exception 'O histórico deste ramo mudou. Atualize a ficha antes de salvar.'
        using errcode='40001';
    end if;
    update public.jovem_historico_ramos
    set data_ingresso=p_data_ingresso,
        data_acolhida=p_data_acolhida,
        data_promessa=p_data_promessa,
        data_inicio_caminho=p_data_inicio_caminho,
        data_passagem=p_data_passagem,
        origem='manual',
        atualizado_em=clock_timestamp(),
        alterado_por=auth.uid()
    where id=v_old.id returning * into v_saved;
  else
    if p_versao_esperada is not null then
      raise exception 'O histórico deste ramo mudou. Atualize a ficha antes de salvar.'
        using errcode='40001';
    end if;
    insert into public.jovem_historico_ramos
      (jovem_id,ramo_id,data_ingresso,data_acolhida,data_promessa,
       data_inicio_caminho,data_passagem,origem,alterado_por)
    values
      (p_jovem_id,p_ramo_id,p_data_ingresso,p_data_acolhida,p_data_promessa,
       p_data_inicio_caminho,p_data_passagem,'manual',auth.uid())
    returning * into v_saved;
  end if;

  -- Espelho compatível apenas dos acontecimentos do ramo atual.
  -- Para outros ramos o histórico anterior fica intocado.
  if p_ramo_id=v_ramo_atual then
    update public.jovens j
    set data_acolhida=p_data_acolhida,
        data_inicio_caminho=p_data_inicio_caminho,
        data_passagem_ramo=p_data_passagem,
        data_promessa_lobinho=case when v_ramo_atual=2
          then p_data_promessa else j.data_promessa_lobinho end,
        data_promessa_escoteira=case when v_ramo_atual=3
          then p_data_promessa else j.data_promessa_escoteira end
    where j.id=p_jovem_id;
  end if;

  return to_jsonb(v_saved);
end;
$body$;

revoke all on function public.salvar_historico_ramo_jovem_v101(
  bigint,bigint,date,date,date,date,date,timestamptz
) from public,anon,authenticated;
grant execute on function public.salvar_historico_ramo_jovem_v101(
  bigint,bigint,date,date,date,date,date,timestamptz
) to authenticated;
