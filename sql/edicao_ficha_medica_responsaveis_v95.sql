-- GEArPC Conecta v95: propostas de correção médica feitas pelos responsáveis.
create table if not exists public.responsavel_propostas_ficha_medica (
  id bigint generated by default as identity primary key,
  responsavel_id bigint not null references public.responsaveis(id) on delete cascade,
  jovem_id bigint not null references public.jovens(id) on delete cascade,
  criado_por uuid not null references auth.users(id),
  base_atualizado_em timestamptz,
  dados_propostos jsonb not null,
  status text not null default 'pendente'
    check (status in ('pendente','aprovada','rejeitada')),
  criado_em timestamptz not null default now(),
  atualizado_em timestamptz not null default now(),
  analisado_por uuid references auth.users(id),
  analisado_em timestamptz,
  justificativa text,
  constraint proposta_medica_json_valido check (
    jsonb_typeof(dados_propostos) = 'object'
    and jsonb_typeof(dados_propostos -> 'dados_completos') = 'object'
    and octet_length(dados_propostos::text) <= 40000
  )
);

create unique index if not exists responsavel_proposta_medica_pendente_un
  on public.responsavel_propostas_ficha_medica (responsavel_id, jovem_id)
  where status = 'pendente';

create index if not exists responsavel_proposta_medica_admin_status_idx
  on public.responsavel_propostas_ficha_medica (status,criado_em desc);

alter table public.responsavel_propostas_ficha_medica enable row level security;

revoke all on public.responsavel_propostas_ficha_medica from anon, authenticated;
grant select, insert on public.responsavel_propostas_ficha_medica to authenticated;
grant update (dados_propostos, base_atualizado_em, atualizado_em)
  on public.responsavel_propostas_ficha_medica to authenticated;
grant usage, select on sequence public.responsavel_propostas_ficha_medica_id_seq to authenticated;

create policy "proposta_medica_ver_autorizados" on public.responsavel_propostas_ficha_medica
for select to authenticated using (
  private.sou_admin()
  or (
    responsavel_id = private.meu_responsavel_id()
    and private.sou_responsavel_jovem(jovem_id)
    and exists (select 1 from public.perfis_usuarios p
      where p.user_id=auth.uid() and p.ativo=true
      and p.tipo='responsavel' and p.eh_teste=true)
  )
);
create policy "proposta_medica_criar_teste" on public.responsavel_propostas_ficha_medica
for insert to authenticated with check (
  status='pendente' and analisado_por is null and analisado_em is null
  and justificativa is null and criado_por=(select auth.uid())
  and responsavel_id=private.meu_responsavel_id()
  and private.sou_responsavel_jovem(jovem_id)
  and exists (select 1 from public.perfis_usuarios p
    where p.user_id=auth.uid() and p.ativo=true
    and p.tipo='responsavel' and p.eh_teste=true)
);
create policy "proposta_medica_reeditar_pendente" on public.responsavel_propostas_ficha_medica
for update to authenticated
using (
  status='pendente' and criado_por=(select auth.uid())
  and responsavel_id=private.meu_responsavel_id()
  and private.sou_responsavel_jovem(jovem_id)
  and exists (select 1 from public.perfis_usuarios p
    where p.user_id=auth.uid() and p.ativo=true
    and p.tipo='responsavel' and p.eh_teste=true)
)
with check (
  status='pendente' and criado_por=(select auth.uid())
  and responsavel_id=private.meu_responsavel_id()
  and private.sou_responsavel_jovem(jovem_id)
  and exists (select 1 from public.perfis_usuarios p
    where p.user_id=auth.uid() and p.ativo=true
    and p.tipo='responsavel' and p.eh_teste=true)
);

-- Uma proposta médica em análise deixa a confirmação anterior pendente.
create or replace function private.proposta_medica_aguardando_administrador()
returns trigger
language plpgsql security definer set search_path = ''
as $body$
begin
  update public.responsavel_confirmacoes_jovens c
    set status='correcao_solicitada',
        observacao='Alterações propostas na ficha médica aguardando aprovação da administração.',
        confirmado_em=null,
        ficha_medica_confirmada_em=null,
        solicitado_em=now(),
        atualizado_em=now()
  where c.responsavel_id=new.responsavel_id and c.jovem_id=new.jovem_id;
  return new;
end
$body$;
revoke all on function private.proposta_medica_aguardando_administrador() from public,anon,authenticated;
create trigger proposta_medica_aguarda_admin
after insert on public.responsavel_propostas_ficha_medica
for each row execute function private.proposta_medica_aguardando_administrador();

-- Aprovação/rejeição atômica: somente o administrador grava na ficha oficial.
create or replace function public.admin_decidir_proposta_medica(
  p_proposta_id bigint, p_aprovar boolean, p_justificativa text default null
)
returns void
language plpgsql security definer set search_path = ''
as $body$
declare
  v_prop public.responsavel_propostas_ficha_medica%rowtype;
  v_med public.fichas_medicas%rowtype;
  v_json jsonb;
  v_now timestamptz := now();
begin
  if auth.uid() is null or not private.sou_admin() then
    raise exception 'Somente a administração pode analisar propostas médicas'
      using errcode='42501';
  end if;
  select * into v_prop from public.responsavel_propostas_ficha_medica
    where id=p_proposta_id for update;
  if not found or v_prop.status<>'pendente' then
    raise exception 'Proposta inexistente ou já analisada';
  end if;
  if p_aprovar then
    select * into v_med from public.fichas_medicas
      where jovem_id=v_prop.jovem_id for update;
    if found then
      if v_med.atualizado_em is distinct from v_prop.base_atualizado_em then
        raise exception 'A ficha médica foi alterada desde a proposta. Peça uma nova revisão.';
      end if;
    elsif v_prop.base_atualizado_em is not null then
      raise exception 'A ficha médica mudou desde a proposta. Peça uma nova revisão.';
    end if;

    v_json:=v_prop.dados_propostos;
    if jsonb_typeof(v_json)<>'object' or jsonb_typeof(v_json->'dados_completos')<>'object'
      or exists (select 1 from jsonb_object_keys(v_json) as x(k)
        where x.k not in ('dados_completos','tipo_sanguineo','alergias','medicamentos_uso_continuo',
          'restricoes_alimentares','condicoes_relevantes','necessidades_especiais',
          'plano_saude','numero_carteirinha','contato_emergencia_nome',
          'contato_emergencia_telefone','observacoes')) then
      raise exception 'Formato de ficha médica inválido';
    end if;
    insert into public.fichas_medicas (
      jovem_id, tipo_sanguineo, alergias, medicamentos_uso_continuo,
      restricoes_alimentares, condicoes_relevantes, necessidades_especiais,
      plano_saude, numero_carteirinha, contato_emergencia_nome,
      contato_emergencia_telefone, observacoes, dados_completos, atualizado_em
    ) values (
      v_prop.jovem_id,
      nullif(v_json->>'tipo_sanguineo',''),
      nullif(v_json->>'alergias',''),
      nullif(v_json->>'medicamentos_uso_continuo',''),
      nullif(v_json->>'restricoes_alimentares',''),
      nullif(v_json->>'condicoes_relevantes',''),
      nullif(v_json->>'necessidades_especiais',''),
      nullif(v_json->>'plano_saude',''),
      nullif(v_json->>'numero_carteirinha',''),
      nullif(v_json->>'contato_emergencia_nome',''),
      nullif(v_json->>'contato_emergencia_telefone',''),
      nullif(v_json->>'observacoes',''),
      v_json->'dados_completos', v_now
    )
    on conflict (jovem_id) do update set
      tipo_sanguineo=excluded.tipo_sanguineo,
      alergias=excluded.alergias,
      medicamentos_uso_continuo=excluded.medicamentos_uso_continuo,
      restricoes_alimentares=excluded.restricoes_alimentares,
      condicoes_relevantes=excluded.condicoes_relevantes,
      necessidades_especiais=excluded.necessidades_especiais,
      plano_saude=excluded.plano_saude,
      numero_carteirinha=excluded.numero_carteirinha,
      contato_emergencia_nome=excluded.contato_emergencia_nome,
      contato_emergencia_telefone=excluded.contato_emergencia_telefone,
      observacoes=excluded.observacoes,
      dados_completos=excluded.dados_completos,
      atualizado_em=excluded.atualizado_em;

    -- Quem enviou a revisão não precisa preencher a ficha duas vezes.
    insert into public.responsavel_confirmacoes_jovens
      (responsavel_id,jovem_id,status,observacao,confirmado_em,solicitado_em,
       confirmado_por,atualizado_em,ficha_medica_confirmada_em)
    values
      (v_prop.responsavel_id,v_prop.jovem_id,'confirmado',null,v_now,null,
       v_prop.criado_por,v_now,v_now)
    on conflict (responsavel_id,jovem_id) do update set
      status='confirmado',observacao=null,confirmado_em=v_now,solicitado_em=null,
      confirmado_por=v_prop.criado_por,atualizado_em=v_now,ficha_medica_confirmada_em=v_now;
  end if;

  update public.responsavel_propostas_ficha_medica
    set status=case when p_aprovar then 'aprovada' else 'rejeitada' end,
        analisado_por=auth.uid(),analisado_em=v_now,
        justificativa=case when p_aprovar then null else left(coalesce(p_justificativa,''),1000) end,
        atualizado_em=v_now
    where id=v_prop.id;
end
$body$;
revoke all on function public.admin_decidir_proposta_medica(bigint,boolean,text)
  from public,anon;
grant execute on function public.admin_decidir_proposta_medica(bigint,boolean,text)
  to authenticated;
